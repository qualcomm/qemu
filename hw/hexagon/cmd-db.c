/*
 * CMD_DB Data Structures
 */

#define NUM_PRIORITY    2
#define MAX_SLV_ID      8

struct entry_header {
    uint8_t id[8];
    uint32_t priority[NUM_PRIORITY];
    uint32_t addr;
    uint16_t len;
    uint16_t offset;
} QEMU_PACKED;

struct rsc_hdr {
    uint16_t slv_id;
    uint16_t header_offset;
    uint16_t data_offset;
    uint16_t cnt;
    uint16_t version;
    uint16_t reserved[3];
} QEMU_PACKED;

struct cmd_db_header {
    uint32_t version;
    uint8_t magic[4];
    struct rsc_hdr header[MAX_SLV_ID];
    uint32_t checksum;
    uint32_t reserved;
    uint8_t data[];
} QEMU_PACKED;

