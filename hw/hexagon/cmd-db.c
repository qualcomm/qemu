static void convert_entry_headers_to_le(struct entry_header *entries,
                                         size_t count)
{
    for (size_t i = 0; i < count; i++) {
        /* Convert priority array */
        for (int j = 0; j < NUM_PRIORITY; j++) {
            entries[i].priority[j] = cpu_to_le32(entries[i].priority[j]);
        }
        /* Convert addr, len, offset */
        entries[i].addr = cpu_to_le32(entries[i].addr);
        entries[i].len = cpu_to_le16(entries[i].len);
        entries[i].offset = cpu_to_le16(entries[i].offset);
    }
}

static void build_cmd_db(uint8_t *buf)
{
    struct cmd_db_header *hdr = (struct cmd_db_header *)buf;

    /* Initialize header */
    hdr->version = cpu_to_le32(0x00000001);
    memcpy(hdr->magic, CMD_DB_MAGIC, sizeof(CMD_DB_MAGIC));

    /* Resource header 0: ARC (slave ID 3) */
    hdr->header[0].slv_id = cpu_to_le16(3);
    hdr->header[0].header_offset = cpu_to_le16(ARC_HEADER_OFFSET);
    hdr->header[0].data_offset = cpu_to_le16(ARC_DATA_OFFSET);
    hdr->header[0].cnt = cpu_to_le16(ARRAY_SIZE(arc_entries));
    hdr->header[0].version = cpu_to_le16(0x1000);

    /* Resource header 1: ARC_MOL (slave ID 3) */
    hdr->header[1].slv_id = cpu_to_le16(3);
    hdr->header[1].header_offset = cpu_to_le16(ARC_MOL_HEADER_OFFSET);
    hdr->header[1].data_offset = cpu_to_le16(ARC_MOL_DATA_OFFSET);
    hdr->header[1].cnt = cpu_to_le16(ARRAY_SIZE(arc_mol_entries));
    hdr->header[1].version = cpu_to_le16(0x1000);

    /* Resource header 2: BCM (slave ID 5) */
    hdr->header[2].slv_id = cpu_to_le16(5);
    hdr->header[2].header_offset = cpu_to_le16(BCM_HEADER_OFFSET);
    hdr->header[2].data_offset = cpu_to_le16(BCM_DATA_OFFSET);
    hdr->header[2].cnt = cpu_to_le16(ARRAY_SIZE(bcm_entries));
    hdr->header[2].version = cpu_to_le16(0x1000);

    /* Resource header 3: VRM (slave ID 4) */
    hdr->header[3].slv_id = cpu_to_le16(4);
    hdr->header[3].header_offset = cpu_to_le16(VRM_HEADER_OFFSET);
    hdr->header[3].data_offset = cpu_to_le16(VRM_DATA_OFFSET);
    hdr->header[3].cnt = cpu_to_le16(ARRAY_SIZE(vrm_entries));
    hdr->header[3].version = cpu_to_le16(0x0100);

    hdr->checksum = cpu_to_le32(0x00000000);
    hdr->reserved = cpu_to_le32(0x00000000);

    /* Copy entry headers and auxiliary data */
    uint8_t *data_ptr = hdr->data;

    /* Assert no overlaps between memory regions */
    g_assert(ARC_HEADER_OFFSET + sizeof(arc_entries) <= ARC_DATA_OFFSET);
    g_assert(ARC_DATA_OFFSET + sizeof(arc_aux_data) <= ARC_MOL_HEADER_OFFSET);
    g_assert(ARC_MOL_HEADER_OFFSET + sizeof(arc_mol_entries) <= ARC_MOL_DATA_OFFSET);
    g_assert(ARC_MOL_DATA_OFFSET + sizeof(arc_mol_aux_data) <= BCM_HEADER_OFFSET);
    g_assert(BCM_HEADER_OFFSET + sizeof(bcm_entries) <= BCM_DATA_OFFSET);
    g_assert(BCM_DATA_OFFSET + sizeof(bcm_aux_data) <= VRM_HEADER_OFFSET);
    g_assert(VRM_HEADER_OFFSET + sizeof(vrm_entries) <= VRM_DATA_OFFSET);

    /* Create little-endian copies of entry headers */
    struct entry_header *arc_entries_le = g_malloc(sizeof(arc_entries));
    memcpy(arc_entries_le, arc_entries, sizeof(arc_entries));
    convert_entry_headers_to_le(arc_entries_le, ARRAY_SIZE(arc_entries));

    struct entry_header *arc_mol_entries_le = g_malloc(sizeof(arc_mol_entries));
    memcpy(arc_mol_entries_le, arc_mol_entries, sizeof(arc_mol_entries));
    convert_entry_headers_to_le(arc_mol_entries_le,
                                 ARRAY_SIZE(arc_mol_entries));

    struct entry_header *bcm_entries_le = g_malloc(sizeof(bcm_entries));
    memcpy(bcm_entries_le, bcm_entries, sizeof(bcm_entries));
    convert_entry_headers_to_le(bcm_entries_le, ARRAY_SIZE(bcm_entries));

    struct entry_header *vrm_entries_le = g_malloc(sizeof(vrm_entries));
    memcpy(vrm_entries_le, vrm_entries, sizeof(vrm_entries));
    convert_entry_headers_to_le(vrm_entries_le, ARRAY_SIZE(vrm_entries));

    /* Copy converted entries and auxiliary data */
    memcpy(data_ptr + ARC_HEADER_OFFSET, arc_entries_le, sizeof(arc_entries));
    memcpy(data_ptr + ARC_DATA_OFFSET, arc_aux_data, sizeof(arc_aux_data));

    memcpy(data_ptr + ARC_MOL_HEADER_OFFSET, arc_mol_entries_le,
           sizeof(arc_mol_entries));
    memcpy(data_ptr + ARC_MOL_DATA_OFFSET, arc_mol_aux_data, sizeof(arc_mol_aux_data));

    memcpy(data_ptr + BCM_HEADER_OFFSET, bcm_entries_le, sizeof(bcm_entries));
    memcpy(data_ptr + BCM_DATA_OFFSET, bcm_aux_data, sizeof(bcm_aux_data));

    memcpy(data_ptr + VRM_HEADER_OFFSET, vrm_entries_le, sizeof(vrm_entries));
    memcpy(data_ptr + VRM_DATA_OFFSET, vrm_aux_data, sizeof(vrm_aux_data));

    /* Free temporary converted copies */
    g_free(arc_entries_le);
    g_free(arc_mol_entries_le);
    g_free(bcm_entries_le);
    g_free(vrm_entries_le);
}

static void build_cmd_db_hdr(uint8_t *buf)
{
    /* Based on reference file analysis, build the header structure */
    uint32_t *header_words = (uint32_t *)buf;

    /* First few words appear to be addresses or offsets */
    header_words[0] = cpu_to_le32(0x0f0040);  /* 40 00 0f 00 */
    header_words[1] = cpu_to_le32(0x0f0048);  /* 48 00 0f 00 */
    header_words[2] = cpu_to_le32(0x0f00a8);  /* a8 00 0f 00 */
    header_words[3] = cpu_to_le32(0x80860000); /* 00 00 86 80 */
    header_words[4] = cpu_to_le32(0x000014d0); /* d0 14 00 00 */
    header_words[5] = cpu_to_le32(0x00000000); /* 00 00 00 00 */
    header_words[6] = cpu_to_le32(0x0f00ac);  /* ac 00 0f 00 */
    header_words[7] = cpu_to_le32(0x0f00b8);  /* b8 00 0f 00 */
    header_words[8] = cpu_to_le32(0x0f01f0);  /* f0 01 0f 00 */

    /* Some resource identifiers found in reference */
    uint32_t *ptr = (uint32_t *)&buf[0x40];
    ptr[0] = cpu_to_le32(0xa0c00c1e);  /* 1e 0c c0 a0 from reference */

    /* Add some resource name strings found in reference */
    memcpy(&buf[0x48], "aosd", 4);
    memcpy(&buf[0x68], "cxsd", 4);
    memcpy(&buf[0x88], "ddr ", 4);
}

void hexagon_load_cmd_db(hwaddr header_addr, hwaddr bin_addr)
{
    uint8_t *cmd_db_header_data, *cmd_db_bin_data;
    size_t cmd_db_bin_size = 0x20000;

    /* Allocate and build header data (1024 bytes) */
    cmd_db_header_data = g_malloc0(CMD_DB_HEADER_SIZE);
    build_cmd_db_hdr(cmd_db_header_data);

    /* Allocate and build full binary data (128KB) */
    cmd_db_bin_data = g_malloc0(cmd_db_bin_size);
    build_cmd_db(cmd_db_bin_data);

    /* Write data directly to physical memory */
    cpu_physical_memory_write(header_addr, cmd_db_header_data,
                              CMD_DB_HEADER_SIZE);
    cpu_physical_memory_write(bin_addr, cmd_db_bin_data, cmd_db_bin_size);

    g_free(cmd_db_header_data);
    g_free(cmd_db_bin_data);
}
